"""
Глава 12, пример 1: Базовый пример агента

Соответствует документации: 12.1.1 Зачем нужна оценка агентов

Этот пример демонстрирует базового агента, способного вызывать
инструмент поиска для выполнения задач.
Но как узнать, насколько хорошо он работает? Именно для этого нужны
системы оценки.
"""

from hello_agents import SimpleAgent, HelloAgentsLLM
from hello_agents.tools import SearchTool

# Создаём LLM и агента
llm = HelloAgentsLLM()

# Создаём системный промпт с акцентом на использование инструментов
system_prompt = """Ты — ИИ-ассистент, который может использовать инструмент поиска для получения актуальной информации.

Когда нужно найти информацию, используй следующий формат:
[TOOL_CALL:search:поисковый запрос]

Например:
- [TOOL_CALL:search:последние новости об ИИ]
- [TOOL_CALL:search:учебник по программированию на Python]

Перед ответом на вопрос сначала используй инструмент поиска для получения актуальной информации."""

agent = SimpleAgent(name="ИИ-ассистент", llm=llm, system_prompt=system_prompt)

# Добавляем инструмент поиска
agent.add_tool(SearchTool())

# Пример: ответ на вопрос с помощью инструмента поиска
print("\nВопрос: Каковы последние тенденции в развитии технологий ИИ?")
print("\nАгент думает и ищет...")
response = agent.run("Каковы последние тенденции в развитии технологий ИИ?")
print(f"\nОтвет: {response}")
