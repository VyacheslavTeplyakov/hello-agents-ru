    @classmethod
    def get_role_desc(cls, role: str) -> str:
        """Получить описание роли"""
        return cls.ROLES.get(role, {}).get("description", "Неизвестная роль")

    @classmethod
    def get_role_ability(cls, role: str) -> str:
        """Получить способность роли"""
        return cls.ROLES.get(role, {}).get("ability", "Нет особых способностей")

    @classmethod
    def get_character_trait(cls, character: str) -> str:
        """Получить черты характера персонажа"""
        return cls.CHARACTER_TRAITS.get(character, "Спокойный характер, вежливая речь")

    @classmethod
    def is_werewolf(cls, role: str) -> bool:
        """Определить, является ли роль оборотнем"""
        return role == "Оборотень"

    @classmethod
    def is_villager_team(cls, role: str) -> bool:
        """Определить, принадлежит ли роль команде мирных"""
        return cls.ROLES.get(role, {}).get("team") == "Команда мирных"

    @classmethod
    def get_standard_setup(cls, player_count: int) -> List[str]:
        """Получить стандартный набор ролей"""
        if player_count == 6:
            return ["Оборотень", "Оборотень", "Провидец", "Ведьма", "Крестьянин", "Крестьянин"]
        elif player_count == 8:
            return ["Оборотень", "Оборотень", "Оборотень", "Провидец", "Ведьма", "Охотник", "Крестьянин", "Крестьянин"]
        elif player_count == 9:
            return ["Оборотень", "Оборотень", "Оборотень", "Провидец", "Ведьма", "Охотник", "Страж", "Крестьянин", "Крестьянин"]
        else:
            # Конфигурация по умолчанию: примерно 1/3 оборотней
            werewolf_count = max(1, player_count // 3)
            roles = ["Оборотень"] * werewolf_count

            # Добавить специальные роли
            remaining = player_count - werewolf_count
            if remaining >= 1:
                roles.append("Провидец")
                remaining -= 1
            if remaining >= 1:
                roles.append("Ведьма")
                remaining -= 1
            if remaining >= 1:
                roles.append("Охотник")
                remaining -= 1

            # Оставшиеся — крестьяне
            roles.extend(["Крестьянин"] * remaining)

            return roles
