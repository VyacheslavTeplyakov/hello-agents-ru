def create_user_proxy():
    """Создать агента-представителя пользователя"""
    return UserProxyAgent(
        name="UserProxy",
        description="""Представитель пользователя, отвечающий за следующее:
1. Формулировать требования к разработке от лица пользователя
2. Выполнять финальную реализацию кода
3. Проверять соответствие функций ожиданиям
4. Предоставлять пользовательскую обратную связь и предложения

После завершения тестирования ответь TERMINATE.""",
    )

async def run_software_development_team():
    """Запустить совместную работу команды разработчиков"""

    print("🔧 Инициализация клиента модели...")

    # Для тестирования используем стандартный клиент OpenAI
    model_client = create_openai_model_client()

    print("👥 Формирование команды агентов...")

    # Создать команду агентов
    product_manager = create_product_manager(model_client)
    engineer = create_engineer(model_client)
    code_reviewer = create_code_reviewer(model_client)
    user_proxy = create_user_proxy()

    # Добавить условие завершения
    termination = TextMentionTermination("TERMINATE")

    # Создать командный чат
    team_chat = RoundRobinGroupChat(
        participants=[
            product_manager,
            engineer,
            code_reviewer,
            user_proxy
        ],
        termination_condition=termination,
        max_turns=20,  # Увеличить максимальное число ходов
    )

    # Определить задание на разработку
    task = """Нам нужно разработать приложение для отображения курса биткоина со следующими требованиями:

Основные функции:
- Отображение текущего курса биткоина в реальном времени (в USD)
- Отображение тренда изменения курса за 24 часа (процент и абсолютное значение)
- Функция обновления курса

Технические требования:
- Использовать фреймворк Streamlit для создания веб-приложения
- Простой и привлекательный интерфейс, удобный для пользователя
- Добавить корректную обработку ошибок и индикатор загрузки

Просьба к команде совместно выполнить эту задачу — от анализа требований до финальной реализации."""

    # Выполнить командную работу
    print("🚀 Запуск командной разработки AutoGen...")
    print("=" * 60)

    # Использовать Console для отображения хода диалога
    result = await Console(team_chat.run_stream(task=task))

    print("\n" + "=" * 60)
    print("✅ Командная работа завершена!")

    return result

# Точка входа
if __name__ == "__main__":
    try:
        # Запустить асинхронный рабочий процесс
        result = asyncio.run(run_software_development_team())

        print(f"\n📋 Сводка результатов:")
        print(f"- Количество агентов: 4")
        print(f"- Статус задания: {'Успешно' if result else 'Требует дополнительной обработки'}")

    except ValueError as e:
        print(f"❌ Ошибка конфигурации: {e}")
        print("Проверьте правильность настроек в файле .env")
    except Exception as e:
        print(f"❌ Ошибка выполнения: {e}")
        import traceback
        traceback.print_exc()


