"""
Пример командной разработки программного обеспечения с AutoGen
"""

import os
import asyncio
from typing import List, Dict, Any
from dotenv import load_dotenv

# Загрузить переменные окружения
load_dotenv()

# Тестируем версию с клиентом OpenAI
from autogen_ext.models.openai import OpenAIChatCompletionClient
from autogen_agentchat.agents import AssistantAgent, UserProxyAgent
from autogen_agentchat.teams import RoundRobinGroupChat
from autogen_agentchat.conditions import TextMentionTermination
from autogen_agentchat.ui import Console

def create_openai_model_client():
    """Создать клиент модели OpenAI для тестирования"""
    return OpenAIChatCompletionClient(
        model=os.getenv("LLM_MODEL_ID", "gpt-4o"),
        api_key=os.getenv("LLM_API_KEY"),
        base_url=os.getenv("LLM_BASE_URL", "https://api.openai.com/v1")
    )

def create_product_manager(model_client):
    """Создать агента-менеджера продукта"""
    system_message = """Ты опытный менеджер продукта, специализирующийся на анализе требований и планировании программных проектов.

Твои основные обязанности:
1. **Анализ требований**: глубокое понимание потребностей пользователей, определение ключевых функций и граничных условий
2. **Техническое планирование**: разработка чёткого пути технической реализации на основе требований
3. **Оценка рисков**: выявление потенциальных технических рисков и проблем с пользовательским опытом
4. **Координация коммуникации**: эффективное взаимодействие с инженерами и другими членами команды

При получении задания на разработку выполни анализ по следующей структуре:
1. Понимание и анализ требований
2. Разделение на функциональные модули
3. Рекомендации по техническому стеку
4. Приоритизация реализации
5. Определение критериев приёмки

Отвечай чётко и лаконично, после завершения анализа скажи «Прошу инженера приступить к реализации»."""

    return AssistantAgent(
        name="ProductManager",
        model_client=model_client,
        system_message=system_message,
    )

