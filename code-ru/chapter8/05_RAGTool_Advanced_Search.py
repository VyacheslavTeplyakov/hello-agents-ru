    def demonstrate_search_performance_analysis(self):
        """Демонстрация анализа производительности поиска"""
        print("\n📊 Анализ производительности поиска")
        print("-" * 50)

        print("Метрики анализа производительности:")
        print("• ⏱️ Сравнение времени отклика")
        print("• 🎯 Оценка качества поиска")
        print("• 💾 Использование ресурсов")
        print("• 📈 Анализ масштабируемости")

        # Запросы для тестирования производительности
        performance_queries = [
            "машинное обучение",
            "алгоритмы оптимизации глубокого обучения",
            "принцип механизма внимания Transformer",
            "сравнение методов детекции объектов в компьютерном зрении"
        ]

        print(f"\n📊 Тест сравнения производительности:")

        # Тест производительности разных стратегий поиска
        strategies = [
            ("Базовый поиск", {"enable_advanced_search": False}),
            ("Продвинутый поиск", {"enable_advanced_search": True})
        ]

        performance_results = {}

        for strategy_name, params in strategies:
            print(f"\nТест производительности «{strategy_name}»:")
            strategy_times = []

            for query in performance_queries:
                start_time = time.time()

                result = self.rag_tool.run({"action":"search",
                                             "query":query,
                                             "limit":3,
                                             **params})

                query_time = time.time() - start_time
                strategy_times.append(query_time)

                print(f"  Запрос: '{query[:20]}...' Время: {query_time:.3f} сек")

            avg_time = sum(strategy_times) / len(strategy_times)
            performance_results[strategy_name] = {
                "times": strategy_times,
                "average": avg_time
            }

            print(f"  Среднее время: {avg_time:.3f} сек")

        # Сравнительный анализ производительности
        print(f"\n📈 Сравнительный анализ производительности:")
        basic_avg = performance_results["Базовый поиск"]["average"]
        advanced_avg = performance_results["Продвинутый поиск"]["average"]

        print(f"Среднее время базового поиска: {basic_avg:.3f} сек")
        print(f"Среднее время продвинутого поиска: {advanced_avg:.3f} сек")
        print(f"Соотношение производительности: {advanced_avg/basic_avg:.1f}x")
        print(f"Анализ: продвинутый поиск повышает качество поиска за счёт множества стратегий, время увеличивается на {((advanced_avg/basic_avg-1)*100):.0f}%")

        # Получение системной статистики
        stats = self.rag_tool.run({"action":"stats"})
        print(f"\n📊 Системная статистика: {stats}")

