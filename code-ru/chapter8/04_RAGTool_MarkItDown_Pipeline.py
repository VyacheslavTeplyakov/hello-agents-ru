        print("2. 🔄 Конвертация в Markdown")
        print("3. 📝 Сохранение структурной информации")
        print("4. ✨ Вывод в унифицированном формате")

        conversion_results = {}

        for filename, file_path in file_paths.items():
            print(f"\nОбработка документа: {filename}")
            print(f"Исходный формат: {os.path.splitext(filename)[1]}")

            start_time = time.time()

            # Добавление документа через RAGTool, внутри вызывается MarkItDown
            result = self.rag_tool.run({"action":"add_document",
                                         "file_path":file_path})

            process_time = time.time() - start_time

            print(f"Результат обработки: {result}")
            print(f"Время обработки: {process_time:.3f} сек")
            print(f"✅ {filename} → Markdown → разбивка → векторизация")

            conversion_results[filename] = {
                "result": result,
                "time": process_time
            }

        return conversion_results

